using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using DotNetAnalysisAndRefactoringMcp.Tools.Json;
using JetBrains.ProjectModel;
using JetBrains.ReSharper.Psi;
using JetBrains.ReSharper.Psi.Caches;
using Newtonsoft.Json.Linq;

namespace DotNetAnalysisAndRefactoringMcp.Tools;

public class BrowseNamespaceTool : IMcpTool
{
   readonly ISolution _solution;

   public BrowseNamespaceTool(ISolution solution) => _solution = solution;

   public string Name => "browse_namespace";
   public ToolAnnotations Annotations => ToolAnnotations.ReadOnly;

   public string Description =>
      "Browse the namespace hierarchy. With no arguments, lists all top-level namespaces. " +
      "With a namespace name, lists its child namespaces and types. " +
      "Enables top-down exploration of the codebase structure. " +
      "Pass multiple namespaces via the 'namespaceNames' array to browse several in one call, and includeMembers: true " +
      "for each type's declared members. With format: 'json': {\"namespaces\": [{name, childNamespaces, types: [{kind, " +
      "name, qualifiedName, file, line, column, members?, nestedTypes}], error?, skipped?}]}, one for each namespace " +
      "asked for, the root when none was. A member is {access?, kind, name, signature, explicitInterface?}, and an " +
      "extension block one of kind 'extension' with a receiver {name?, type, typeName} and members of its own.";

   public object InputSchema => new
                                {
                                   type = "object",
                                   properties = new
                                                {
                                                   namespaceName = new
                                                                   {
                                                                      type = "string",
                                                                      description = "Namespace to browse (e.g. 'MyApp.Core'). Omit or leave empty to list top-level namespaces."
                                                                   },
                                                   namespaceNames = new
                                                                    {
                                                                       type = "array",
                                                                       description = "Array of namespace names to browse in batch. Results are concatenated with separators. Alternative to single 'namespaceName' parameter.",
                                                                       items = new { type = "string" }
                                                                    },
                                                   includeMembers = new
                                                                    {
                                                                       type = "boolean",
                                                                       description = "List each type's declared members: not inherited, nor generated by the compiler. Default: false."
                                                                    },
                                                   format = JsonFormat.Argument
                                                },
                                   required = Array.Empty<string>()
                                };

   public object Execute(JObject arguments) =>
      JsonFormat.IsAskedFor(arguments)
         ? new NamespacesJson([.. NamespaceNamesIn(arguments).Select(name => NamespaceJsonOf(name, arguments["includeMembers"]?.Value<bool>() == true))])
         : ToolBatch.Of(arguments, "namespaceNames", item: "namespaceName")?.Run(ExecuteSingle) ?? ExecuteSingle(arguments);

   static IEnumerable<string> NamespaceNamesIn(JObject arguments) =>
      (arguments["namespaceNames"] as JArray)?.Select(it => it.ToString()).ToList() is { Count: > 0 } names
         ? names
         : [arguments["namespaceName"]?.ToString() ?? ""];

   ISymbolScope SymbolScope => _solution.GetPsiServices().Symbols.GetSymbolScope(LibrarySymbolScope.NONE, caseSensitive: true);

   /// <summary>The namespace of <paramref name="namespaceName"/>, the root for an empty name; nothing for one the solution doesn't have.</summary>
   INamespace NamespaceNamed(string namespaceName) =>
      string.IsNullOrEmpty(namespaceName) ? SymbolScope.GlobalNamespace : FindNamespace(SymbolScope, namespaceName);

   /// <summary>The types directly in <paramref name="ns"/>, not nested in another type, by name.</summary>
   List<ITypeElement> TypesIn(INamespace ns, SkippedElements skipped)
   {
      var types = new List<ITypeElement>();
      foreach(var typeElement in ns.GetNestedTypeElements(SymbolScope))
         skipped.Guard(typeElement,
                       () =>
                       {
                          if(typeElement.GetContainingType() == null)
                             types.Add(typeElement);
                       });
      return [.. types.OrderBy(it => it.ShortName)];
   }

   NamespaceJson NamespaceJsonOf(string namespaceName, bool withMembers)
   {
      if(NamespaceNamed(namespaceName) is not { } ns)
         return NamespaceJson.NotFound(namespaceName);

      var skipped = new SkippedElements();
      var types = new List<TypeJson>();
      foreach(var type in TypesIn(ns, skipped))
         skipped.Guard(type, () => types.Add(TypeJson.Of(type, withMembers)));

      return NamespaceJson.Of(namespaceName,
                              [.. ns.GetNestedNamespaces(SymbolScope).Select(it => it.QualifiedName).OrderBy(it => it)],
                              types,
                              skipped.Line);
   }

   object ExecuteSingle(JObject arguments)
   {
      var namespaceName = arguments["namespaceName"]?.ToString() ?? "";
      var withMembers = arguments["includeMembers"]?.Value<bool>() == true;
      var symbolScope = SymbolScope;
      var targetNs = NamespaceNamed(namespaceName);
      if(targetNs == null)
         return new { error = $"Namespace not found: {namespaceName}" };

      // Format compact output
      var sb = new StringBuilder();
      var skipped = new SkippedElements();
      var displayName = string.IsNullOrEmpty(namespaceName) ? "(root)" : namespaceName;
      sb.Append("namespace: ").Append(displayName).Append('\n');

      // Child namespaces
      var childNamespaces = targetNs.GetNestedNamespaces(symbolScope)
                                    .OrderBy(ns => ns.ShortName)
                                    .ToList();

      if(childNamespaces.Count > 0)
      {
         sb.Append('\n');
         sb.Append("child namespaces:").Append('\n');
         foreach(var childNs in childNamespaces)
         {
            skipped.Guard(childNs.QualifiedName,
                          () =>
                          {
                             var typeCount = childNs.GetNestedTypeElements(symbolScope).Count();
                             sb.Append("  ").Append(childNs.QualifiedName);
                             sb.Append(" (").Append(typeCount).Append(" types)").Append('\n');
                          });
         }
      }

      var types = TypesIn(targetNs, skipped);
      if(types.Count > 0)
      {
         sb.Append('\n');
         sb.Append("types:").Append('\n');
         foreach(var typeElement in types)
            skipped.Guard(typeElement,
                          () =>
                          {
                             sb.Append(TypeLine(typeElement));
                             if(withMembers) new MemberListing(typeElement).AppendTo(sb, "    ");
                          });
      }

      if(skipped.Line != null)
         sb.Append('\n').Append(skipped.Line).Append('\n');

      return sb.ToString().TrimEnd();
   }

   static string TypeLine(ITypeElement typeElement)
   {
      var sb = new StringBuilder();
      sb.Append("  ").Append(typeElement.GetElementType().PresentableName);
      sb.Append(' ').Append(typeElement.ShortName);

      if(MainDeclaration.Of(typeElement) is {} decl)
      {
         var sf = decl.GetSourceFile();
         if(sf != null)
         {
            var fileName = Path.GetFileName(sf.GetLocation().FullPath);
            if(IsGeneratedFile(fileName))
               sb.Append(" [generated]");

            sb.Append(" — ").Append(fileName);

            var site = DeclarationSite.Of(decl);
            if(site != null)
               sb.Append(':').Append(site.Line);
         }
      }

      return sb.Append('\n').ToString();
   }

   static bool IsGeneratedFile(string fileName)
   {
      return fileName.EndsWith(".g.cs") ||
             fileName.EndsWith(".g.fs") ||
             fileName.EndsWith(".generated.cs") ||
             fileName.EndsWith(".designer.cs", System.StringComparison.OrdinalIgnoreCase) ||
             fileName.EndsWith(".g.i.cs") ||
             fileName == "AssemblyInfo.cs" ||
             fileName == "AssemblyAttributes.cs" ||
             fileName.EndsWith(".razor.g.cs");
   }

   static INamespace FindNamespace(ISymbolScope symbolScope, string qualifiedName)
   {
      var parts = qualifiedName.Split('.');
      var current = symbolScope.GlobalNamespace;

      foreach(var part in parts)
      {
         INamespace found = null;
         foreach(var child in current.GetNestedNamespaces(symbolScope))
         {
            if(child.ShortName == part)
            {
               found = child;
               break;
            }
         }

         if(found == null) return null;
         current = found;
      }

      return current;
   }
}
