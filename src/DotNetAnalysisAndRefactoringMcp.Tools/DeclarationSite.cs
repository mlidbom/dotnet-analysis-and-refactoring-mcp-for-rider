#nullable enable
using System;
using System.Linq;
using JetBrains.ReSharper.Psi;
using JetBrains.ReSharper.Psi.Tree;

namespace DotNetAnalysisAndRefactoringMcp;

/// <summary>
///   Where a declaration is, as an editor's go-to-declaration puts the caret: its file, and the line and column of
///   its name.
/// </summary>
/// <remarks>
///   Not the start of the declaration's own range, which includes its doc comment and attributes: until 2026-11-14
///   the tools gave the first line of a type's doc comment as the line it is declared on.
/// </remarks>
public sealed class DeclarationSite
{
   /// <summary>The file's full path; empty for a declaration whose file has none.</summary>
   public string File { get; }

   /// <summary>For a declaration in a file a source generator wrote, which has no path, that file.</summary>
   public GeneratedFile? GeneratedFile { get; }

   /// <summary>1-based.</summary>
   public int Line { get; }

   /// <summary>1-based.</summary>
   public int Column { get; }

   DeclarationSite(string file, GeneratedFile? generatedFile, int line, int column)
   {
      File = file;
      GeneratedFile = generatedFile;
      Line = line;
      Column = column;
   }

   /// <summary>
   ///   As the text answers write it: <c>Shapes\Palette.cs:9</c>, the path relative to <paramref name="root"/>, or
   ///   <c>[generated by Shapes.Generators.SwatchGenerator] Swatch.g.cs:6</c> in a <see cref="GeneratedFile"/>.
   /// </summary>
   public string Location(SolutionRoot root) => $"{FileAsWritten(root)}:{Line}";

   /// <summary>As <see cref="Location"/>, with the column: <c>Shapes\Palette.cs:9:17</c>.</summary>
   public string LocationWithColumn(SolutionRoot root) => $"{Location(root)}:{Column}";

   string FileAsWritten(SolutionRoot root) => GeneratedFile?.Name ?? root.Relative(File);

   /// <summary>Nothing for a declaration without a source file or a range in it.</summary>
   public static DeclarationSite? Of(IDeclaration declaration)
   {
      var sourceFile = declaration.GetSourceFile();
      if(sourceFile == null)
         return null;

      var range = declaration.GetNameDocumentRange();
      if(!range.IsValid())
         range = TreeNodeExtensions.GetDocumentRange(declaration);
      if(!range.IsValid())
         return null;

      var (line, column) = PsiHelpers.GetLineColumn(range.StartOffset);
      return new DeclarationSite(sourceFile.GetLocation().FullPath, DotNetAnalysisAndRefactoringMcp.GeneratedFile.Of(sourceFile), line, column);
   }

   /// <summary>
   ///   The site of the element's <see cref="MainDeclaration"/> in a file with a path, or else of its first other one
   ///   there; nothing for compiled elements.
   /// </summary>
   public static DeclarationSite? WhereDeclaredInAFileWithAPath(IDeclaredElement element) =>
      MainDeclaration.InOrder(element).Select(Of).FirstOrDefault(it => it is { File.Length: > 0 });

   /// <summary>
   ///   The site of the element's <see cref="MainDeclaration"/>, or else of its declaration in a
   ///   <see cref="GeneratedFile"/>, or for a member with no declaration of its own, where it is written: a positional
   ///   record's property at the parameter of the same name in its type's header, anything else, such as an implicit
   ///   constructor, at its type's name. Nothing for compiled elements.
   /// </summary>
   /// <remarks>
   ///   Until 2026-11-26 a member a source generator wrote into a partial type was at the type's name, in the file of
   ///   the type's part that the solution declares.
   /// </remarks>
   public static DeclarationSite? WhereWritten(IDeclaredElement element) =>
      WhereDeclared(element) ?? WhereAMemberWithoutADeclarationIsWritten(element, WhereDeclared);

   /// <summary>
   ///   As <see cref="WhereWritten"/>, but of the declarations in files with a path only: a member a source generator
   ///   wrote into a partial type is at the type's name, and one of a wholly generated type is nowhere. What the JSON form
   ///   gives, which the .NET Terminal Symbol Linker reads.
   /// </summary>
   public static DeclarationSite? WhereWrittenInAFileWithAPath(IDeclaredElement element) =>
      WhereDeclaredInAFileWithAPath(element) ?? WhereAMemberWithoutADeclarationIsWritten(element, WhereDeclaredInAFileWithAPath);

   /// <summary>
   ///   The site of the element's <see cref="MainDeclaration"/> in a file with a path, or else of its declaration in a
   ///   <see cref="GeneratedFile"/>; nothing for one with no declaration.
   /// </summary>
   public static DeclarationSite? WhereDeclared(IDeclaredElement element) =>
      WhereDeclaredInAFileWithAPath(element) ?? MainDeclaration.InOrder(element).Select(Of).FirstOrDefault(it => it?.GeneratedFile != null);

   static DeclarationSite? WhereAMemberWithoutADeclarationIsWritten(IDeclaredElement element, Func<IDeclaredElement, DeclarationSite?> whereDeclared)
   {
      if(element is not ITypeMember member || element is ITypeElement || member.ContainingType is not { } type)
         return null;

      return type.Constructors
                 .SelectMany(it => it.Parameters)
                 .Where(it => it.ShortName == member.ShortName)
                 .Select(whereDeclared)
                 .FirstOrDefault(it => it != null)
          ?? whereDeclared(type);
   }
}
